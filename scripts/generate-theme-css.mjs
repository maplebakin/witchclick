#!/usr/bin/env node

/**
 * Theme to CSS Bridge
 * Auto-generates CSS custom properties from theme JSON files
 *
 * Usage:
 *   node scripts/generate-theme-css.mjs
 *   npm run themes:build
 */

import { readFileSync, writeFileSync, readdirSync, watch } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = join(__dirname, '..');

// Paths
const THEMES_DIR = join(ROOT, 'content', 'themes');
const OUTPUT_FILE = join(ROOT, 'src', 'styles', 'themes.generated.css');

/**
 * Convert camelCase to kebab-case for CSS properties
 */
function toKebabCase(str) {
  return str.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

/**
 * Generate CSS custom properties from theme settings
 */
function generateThemeCSS(theme) {
  const { slug, label, mode, settings } = theme;

  const properties = Object.entries(settings)
    .map(([key, value]) => {
      const cssVar = toKebabCase(key);
      return `  --theme-${cssVar}: ${value};`;
    })
    .join('\n');

  return `
/* ${label} (${mode} mode) */
:root[data-theme="${slug}"] {
${properties}
}`;
}

/**
 * Load all theme JSON files
 */
function loadThemes() {
  const themes = [];
  const files = readdirSync(THEMES_DIR).filter(f =>
    f.endsWith('.json') && f !== 'active.json'
  );

  for (const file of files) {
    try {
      const content = readFileSync(join(THEMES_DIR, file), 'utf-8');
      const theme = JSON.parse(content);

      // Validate theme structure
      if (!theme.slug || !theme.settings) {
        console.warn(`⚠️  Skipping ${file}: missing required fields`);
        continue;
      }

      themes.push(theme);
    } catch (error) {
      console.error(`❌ Error reading ${file}:`, error.message);
    }
  }

  return themes;
}

/**
 * Generate complete CSS file with all themes
 */
function generateCSS(themes) {
  const header = `/**
 * AUTO-GENERATED THEME CSS
 *
 * This file is automatically generated from JSON theme files.
 * DO NOT EDIT MANUALLY - your changes will be overwritten.
 *
 * To modify themes, edit files in content/themes/
 * Then run: npm run themes:build
 *
 * Generated: ${new Date().toISOString()}
 * Source: scripts/generate-theme-css.mjs
 */

/* ========================================================================
   Theme Custom Properties
   ======================================================================== */
`;

  const defaultSection = `
/* ========================================================================
   Default Theme Mappings

   These map theme-specific tokens to the design system.
   Override these in your components to use theme colors.
   ======================================================================== */

:root {
  /* Map to design tokens when no theme is active */
  --theme-primary: var(--color-amethyst, #7c4eb0);
  --theme-accent: var(--color-gold, #d4af37);
  --theme-background: var(--color-midnight, #07020f);
  --theme-text-primary: var(--color-ink, #f4f1ff);
  --theme-text-heading: var(--color-rune, #f8f3ff);
  --theme-text-muted: var(--color-muted, rgba(244, 241, 255, 0.72));
  --theme-font-serif: var(--font-body-serif, "Lora", Georgia, serif);
  --theme-font-script: var(--font-accent, "Cormorant Garamond", serif);
}
`;

  const themeCSS = themes
    .sort((a, b) => {
      // Sort: default first, then by mode, then alphabetically
      if (a.category === 'default' && b.category !== 'default') return -1;
      if (b.category === 'default' && a.category !== 'default') return 1;
      if (a.mode !== b.mode) return a.mode.localeCompare(b.mode);
      return a.label.localeCompare(b.label);
    })
    .map(generateThemeCSS)
    .join('\n');

  const utilitySection = `

/* ========================================================================
   Theme Utilities
   ======================================================================== */

/* Apply theme colors to body background */
body[data-theme] {
  background-color: var(--theme-background);
  transition: background-color 300ms ease;
}

/* Theme-aware text colors */
.theme-text-primary {
  color: var(--theme-text-primary);
}

.theme-text-heading {
  color: var(--theme-text-heading);
}

.theme-text-muted {
  color: var(--theme-text-muted);
}

/* Theme-aware surface */
.theme-surface {
  background: var(--theme-primary);
  opacity: 0.08;
}

.theme-border {
  border-color: var(--theme-accent);
  opacity: 0.3;
}

/* Theme preview swatch (for UI) */
.theme-swatch {
  display: inline-block;
  width: 2rem;
  height: 2rem;
  border-radius: 0.5rem;
  border: 1px solid rgba(0, 0, 0, 0.1);
  background: linear-gradient(135deg,
    var(--theme-primary) 0%,
    var(--theme-accent) 100%
  );
}
`;

  return header + defaultSection + themeCSS + utilitySection;
}

/**
 * Generate theme metadata JSON for runtime use
 */
function generateMetadata(themes) {
  const metadata = {
    generated: new Date().toISOString(),
    count: themes.length,
    themes: themes.map(t => ({
      slug: t.slug,
      label: t.label,
      mode: t.mode,
      category: t.category,
    }))
  };

  const metadataFile = join(ROOT, 'src', 'data', 'themes.generated.json');
  writeFileSync(metadataFile, JSON.stringify(metadata, null, 2));

  return metadataFile;
}

/**
 * Main execution
 */
function runGeneration() {
  console.log('🎨 Generating theme CSS...\n');

  // Load themes
  const themes = loadThemes();
  console.log(`📦 Loaded ${themes.length} themes:`);
  themes.forEach(t => {
    console.log(`   • ${t.label} (${t.slug}) - ${t.mode} mode`);
  });

  // Generate CSS
  const css = generateCSS(themes);
  writeFileSync(OUTPUT_FILE, css, 'utf-8');
  console.log(`\n✅ Generated CSS: ${OUTPUT_FILE}`);

  // Generate metadata
  const metadataFile = generateMetadata(themes);
  console.log(`✅ Generated metadata: ${metadataFile}`);

  // Summary
  console.log(`\n📊 Summary:`);
  console.log(`   • Total themes: ${themes.length}`);
  console.log(`   • Midnight themes: ${themes.filter(t => t.mode === 'midnight').length}`);
  console.log(`   • Dawn themes: ${themes.filter(t => t.mode === 'dawn').length}`);
  console.log(`   • CSS properties per theme: ${Object.keys(themes[0]?.settings || {}).length}`);

  console.log(`\n✨ Theme CSS generation complete!\n`);
}

function parseFlags(argv) {
  const flags = new Set(argv);
  return {
    watch: flags.has('--watch') || flags.has('-w')
  };
}

function startWatcher() {
  console.log(`👀 Watching ${THEMES_DIR} for changes. Press Ctrl+C to exit.`);

  let rebuildTimer = null;

  const scheduleRebuild = (eventType, filename) => {
    const detail = [eventType, filename].filter(Boolean).join(': ');
    if (rebuildTimer) {
      clearTimeout(rebuildTimer);
    }
    rebuildTimer = setTimeout(() => {
      console.log(`\n🔁 Change detected${detail ? ` (${detail})` : ''}. Rebuilding...`);
      try {
        runGeneration();
        console.log('✅ Rebuild complete. Continuing to watch for changes.');
      } catch (error) {
        console.error('❌ Rebuild failed:', error);
        console.log('⚠️ Watcher will continue running.');
      } finally {
        rebuildTimer = null;
      }
    }, 100);
  };

  const watcher = watch(THEMES_DIR, (eventType, filename) => {
    scheduleRebuild(eventType, filename);
  });

  watcher.on('error', error => {
    console.error('❌ Theme watcher error:', error);
  });

  const handleExit = () => {
    console.log('\n👋 Received SIGINT. Stopping theme watcher.');
    watcher.close();
    process.exit(0);
  };

  process.on('SIGINT', handleExit);
}

// Run if called directly
if (import.meta.url === `file://${process.argv[1]}`) {
  const flags = parseFlags(process.argv.slice(2));
  let initialRunFailed = false;

  try {
    runGeneration();
  } catch (error) {
    initialRunFailed = true;
    console.error('❌ Theme CSS generation failed:', error);
    if (!flags.watch) {
      process.exit(1);
    } else {
      process.exitCode = 1;
      console.log('⚠️ Watch mode will continue despite the failure.');
    }
  }

  if (flags.watch) {
    if (initialRunFailed) {
      console.log('🔁 Waiting for changes before attempting to rebuild again.');
    }
    startWatcher();
  }
}

export { loadThemes, generateCSS, generateThemeCSS, runGeneration };
